#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(repoRoot, 'bundle', 'wix', 'assets.wxi');
const assetRoots = ['data'];

function xml(value) {
  return value.replaceAll('&', '&amp;').replaceAll("'", '&apos;').replaceAll('<', '&lt;');
}

function id(prefix, value) {
  return `${prefix}${createHash('sha256').update(value).digest('hex').slice(0, 16)}`;
}

function directoryTree(path) {
  return readdirSync(path, { withFileTypes: true })
    .sort((left, right) => left.name.localeCompare(right.name))
    .map((entry) => ({
      name: entry.name,
      kind: entry.isDirectory() ? 'directory' : 'file',
      children: entry.isDirectory() ? directoryTree(join(path, entry.name)) : [],
    }));
}

function renderDirectory(root, entries, ancestorPath, indent, components) {
  const logicalPath = ancestorPath.join('/');
  const lines = [`${indent}<Directory Id='${id('AssetDirectory', logicalPath)}' Name='${xml(root)}'>`];
  for (const entry of entries) {
    const entryPath = [...ancestorPath, entry.name];
    if (entry.kind === 'directory') {
      lines.push(...renderDirectory(entry.name, entry.children, entryPath, `${indent}  `, components));
      continue;
    }

    const relativePath = entryPath.join('/');
    const componentId = id('AssetComponent', relativePath);
    const source = ['$(var.CargoTargetBinDir)', '..', '..', '..', ...entryPath].join('\\');
    components.push(componentId);
    lines.push(
      `${indent}  <Component Id='${componentId}' Guid='*'>`,
      `${indent}    <File Id='${id('AssetFile', relativePath)}' Name='${xml(entry.name)}' Source='${xml(source)}' KeyPath='yes'/>`,
      `${indent}  </Component>`,
    );
  }
  lines.push(`${indent}</Directory>`);
  return lines;
}

function render() {
  const components = [];
  const directories = assetRoots.flatMap((root) =>
    renderDirectory(root, directoryTree(join(repoRoot, root)), [root], '    ', components),
  );
  const componentRefs = components.map((component) => `    <ComponentRef Id='${component}'/>`);
  return [
    '<!-- Generated by scripts/generate_wix_assets.mjs; do not edit. -->',
    '<Include>',
    '<Fragment>',
    "  <DirectoryRef Id='APPLICATIONFOLDER'>",
    ...directories,
    '  </DirectoryRef>',
    "  <ComponentGroup Id='PackageAssets'>",
    ...componentRefs,
    '  </ComponentGroup>',
    '</Fragment>',
    '</Include>',
    '',
  ].join('\n');
}

const output = render();
if (process.argv.includes('--stdout')) {
  process.stdout.write(output);
} else if (process.argv.includes('--check')) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== output) {
    console.error(`stale WiX asset manifest: ${relative(repoRoot, outputPath)}`);
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, output);
}
